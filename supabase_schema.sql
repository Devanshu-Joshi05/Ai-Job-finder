-- ========================================================
-- TalentAI: Clean & Bulletproof Supabase Setup
-- Safe to run multiple times (Idempotent)
-- ========================================================

-- Enable UUID extension
create extension if not exists "uuid-ossp";

-- 1. Create PROFILES Table
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  full_name text not null,
  email text not null,
  target_role text default 'Software Engineer',
  location text default 'Remote / India',
  skills text[] default '{}',
  resume_url text,
  profile_strength integer default 85,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Create JOBS Table
create table if not exists public.jobs (
  id bigint generated by default as identity primary key,
  title text not null,
  company text not null,
  logo text default '💼',
  location text not null,
  type text not null,
  mode text not null,
  salary text not null,
  experience text not null,
  match_score integer default 85,
  matching_skills text[] default '{}',
  missing_skills text[] default '{}',
  why_match text,
  description text not null,
  apply_url text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 3. Create SAVED_JOBS Table
create table if not exists public.saved_jobs (
  id uuid default uuid_generate_v4() primary key,
  user_id uuid references auth.users on delete cascade not null,
  job_id bigint references public.jobs on delete cascade not null,
  saved_at timestamp with time zone default timezone('utc'::text, now()) not null,
  unique (user_id, job_id)
);

-- 4. Create APPLICATIONS Table
create table if not exists public.applications (
  id uuid default uuid_generate_v4() primary key,
  user_id uuid references auth.users on delete cascade not null,
  job_id bigint references public.jobs on delete cascade not null,
  stage text not null default 'Applied',
  notes text default 'Applied via TalentAI',
  applied_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- ========================================================
-- Enable Row Level Security (RLS)
-- ========================================================
alter table public.profiles enable row level security;
alter table public.jobs enable row level security;
alter table public.saved_jobs enable row level security;
alter table public.applications enable row level security;

-- ========================================================
-- Clean Policies (Drop if exists, then create safely)
-- ========================================================

-- Jobs policies
drop policy if exists "Allow public read access to jobs" on public.jobs;
create policy "Allow public read access to jobs"
  on public.jobs for select
  using (true);

-- Profiles policies
drop policy if exists "Users can view own profile" on public.profiles;
create policy "Users can view own profile"
  on public.profiles for select
  using (auth.uid() = id);

drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile"
  on public.profiles for update
  using (auth.uid() = id);

drop policy if exists "Users can insert own profile" on public.profiles;
create policy "Users can insert own profile"
  on public.profiles for insert
  with check (auth.uid() = id);

-- Saved Jobs policies
drop policy if exists "Users can view own saved jobs" on public.saved_jobs;
create policy "Users can view own saved jobs"
  on public.saved_jobs for select
  using (auth.uid() = user_id);

drop policy if exists "Users can insert own saved jobs" on public.saved_jobs;
create policy "Users can insert own saved jobs"
  on public.saved_jobs for insert
  with check (auth.uid() = user_id);

drop policy if exists "Users can delete own saved jobs" on public.saved_jobs;
create policy "Users can delete own saved jobs"
  on public.saved_jobs for delete
  using (auth.uid() = user_id);

-- Applications policies
drop policy if exists "Users can view own applications" on public.applications;
create policy "Users can view own applications"
  on public.applications for select
  using (auth.uid() = user_id);

drop policy if exists "Users can insert own applications" on public.applications;
create policy "Users can insert own applications"
  on public.applications for insert
  with check (auth.uid() = user_id);

drop policy if exists "Users can update own applications" on public.applications;
create policy "Users can update own applications"
  on public.applications for update
  using (auth.uid() = user_id);

drop policy if exists "Users can delete own applications" on public.applications;
create policy "Users can delete own applications"
  on public.applications for delete
  using (auth.uid() = user_id);
